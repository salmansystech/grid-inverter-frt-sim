function S = scenarios()
%SCENARIOS The test matrix: grid events with pass/fail criteria.
%   Every scenario starts the same way (enable at 0.1 s, 10 kW ramp from
%   0.15 s to 0.25 s) and applies its event at 0.45 s, once the DC link has
%   settled. Limits and their rationale are in docs/TEST_PLAN.md.

% Checked in every scenario
base = {'i_sustained_pu', '<=', 1.20;
        'vdc_max_pu',     '<=', 1.15;
        'vdc_min_pu',     '>=', 0.90;
        'p_err_final',    '<=', 0.02};

% Added for fault ride-through scenarios
frt = {'i_peak_pu',    '<=', 2.00;
       'iq_rise',      '<=', 0.03;
       'iq_track_err', '<=', 0.05;
       'p_recovery',   '<=', 0.10};

fault = {'Tend', 1.0, 't_fault', 0.45, 't_clear', 0.60};

S = make_scenario('steady_state', ...
    'description', 'Start-up and 10 kW export on a stiff grid', ...
    'criteria', [base; {'p_err_pre', '<=', 0.02; 'vdc_err_pre', '<=', 0.01; ...
                        'p_osc', '<=', 0.01; 'q_err_final', '<=', 0.02}]);

S(end+1) = make_scenario('q_step', ...
    'description', '5 kvar reactive power step at full active power', ...
    'Tend', 0.7, 'Q_set', 5e3, 't_Q', 0.45, ...
    'criteria', [base; {'q_settle', '<=', 0.02; 'q_err_final', '<=', 0.03}]);

S(end+1) = make_scenario('sym_dip_50', fault{:}, ...
    'description', 'Three-phase dip to 50 % for 150 ms', ...
    'u_fault', [0.5, 0.5, 0.5], 'criteria', [base; frt]);

S(end+1) = make_scenario('sym_dip_20', fault{:}, ...
    'description', 'Three-phase dip to 20 % for 150 ms', ...
    'u_fault', [0.2, 0.2, 0.2], 'criteria', [base; frt]);

S(end+1) = make_scenario('sym_dip_05', fault{:}, ...
    'description', 'Near-zero voltage ride-through, 5 % for 150 ms', ...
    'u_fault', [0.05, 0.05, 0.05], 'criteria', [base; frt]);

S(end+1) = make_scenario('asym_1ph_20', fault{:}, ...
    'description', 'Single-phase dip, phase a to 20 % for 150 ms', ...
    'u_fault', [0.2, 1, 1], 'criteria', [base; frt]);

S(end+1) = make_scenario('asym_2ph_50', fault{:}, ...
    'description', 'Two-phase dip, phases b and c to 50 % for 150 ms', ...
    'u_fault', [1, 0.5, 0.5], 'criteria', [base; frt]);

S(end+1) = make_scenario('phase_jump_20', ...
    'description', '20 degree phase jump of the grid voltage', ...
    'Tend', 0.8, 't_jump', 0.45, 'jump_deg', 20, ...
    'criteria', [base; {'pll_settle', '<=', 0.10}]);

S(end+1) = make_scenario('freq_step', ...
    'description', 'Grid frequency step 50 Hz -> 49.5 Hz', ...
    'Tend', 0.9, 't_fstep', 0.45, 'f_step', 49.5, ...
    'criteria', [base; {'f_settle', '<=', 0.15; 'f_err_final', '<=', 0.01}]);

S(end+1) = make_scenario('weak_scr3', ...
    'description', 'Full power export into a weak grid (SCR 3)', ...
    'SCR', 3, ...
    'criteria', [base; {'p_err_pre', '<=', 0.02; 'p_osc', '<=', 0.01}]);

% Weak grid: slower reactive current build-up and more post-fault
% overshoot are expected, so two limits are relaxed.
weak_frt = [base; frt];
weak_frt{strcmp(weak_frt(:, 1), 'i_sustained_pu'), 3} = 1.25;
weak_frt{strcmp(weak_frt(:, 1), 'iq_rise'), 3} = 0.05;
S(end+1) = make_scenario('weak_scr3_dip50', fault{:}, ...
    'description', 'Three-phase dip to 50 % on a weak grid (SCR 3)', ...
    'SCR', 3, 'u_fault', [0.5, 0.5, 0.5], 'criteria', weak_frt);
end
